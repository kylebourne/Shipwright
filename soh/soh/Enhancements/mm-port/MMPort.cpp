namespace MMPort {

// Real init function for each generated actor, by the id ActorDB gave it.
static std::unordered_map<s16, ActorFunc> sRealInit;

// Any asset that is always in mm.o2r will do; if it isn't there, the player never extracted Majora's Mask.
static bool AssetsLoaded() {
    return ResourceMgr_FileExists("__OTR__mm/objects/object_tree/gTreeBodyDL");
}

static void GuardedInit(Actor* actor, PlayState* play) {
    auto it = sRealInit.find(actor->id);
    if (!AssetsLoaded() || it == sRealInit.end()) {
        // Nothing to draw or collide with: remove it without running its destroy on an uninitialised actor.
        actor->destroy = NULL;
        Actor_Kill(actor);
        return;
    }
    it->second(actor, play);
}

static void RegisterGenerated(const ActorInit& init, const char* name, const char* desc) {
    ActorDBInit entry;
    entry.name = name;
    entry.desc = desc;
    entry.id = -1;
    entry.category = init.category;
    entry.flags = init.flags;
    entry.objectId = init.objectId;
    entry.instanceSize = init.instanceSize;
    entry.init = GuardedInit;
    entry.destroy = init.destroy;
    entry.update = init.update;
    entry.draw = init.draw;
    entry.reset = nullptr;
    ActorDB::Entry& added = ActorDB::Instance->AddEntry(entry);
    sRealInit[(s16)added.entry.id] = init.init;
}

// Each ported actor gets the next free id (-1). Its asset paths are self-contained strings, so it
// borrows gameplay_keep as its object instead of needing an entry in Ocarina's object table.
void RegisterActors() {
    static bool registered = false;
    if (registered) {
        return;
    }
    registered = true;

    // Hand-ported (M1, M2).
    ActorDBInit tree = {
        "Mm_Obj_Tree",
        "MM: Clock Town Tree",
        -1,
        ACTORCAT_PROP,
        ACTOR_FLAG_UPDATE_DURING_OCARINA,
        OBJECT_GAMEPLAY_KEEP,
        sizeof(MmObjTree),
        (ActorFunc)MmObjTree_Init,
        (ActorFunc)MmObjTree_Destroy,
        (ActorFunc)MmObjTree_Update,
        (ActorFunc)MmObjTree_Draw,
        nullptr,
    };
    ActorDB::Instance->AddEntry(tree);

    // params: 0 = Black Boe, 1 = White Boe. Add 4 to make it respawn after dying.
    ActorDBInit boe = {
        "Mm_En_Mkk",
        "MM: Boe (Black/White)",
        -1,
        ACTORCAT_ENEMY,
        ACTOR_FLAG_ATTENTION_ENABLED | ACTOR_FLAG_HOSTILE,
        OBJECT_GAMEPLAY_KEEP,
        sizeof(MmEnMkk),
        (ActorFunc)MmEnMkk_Init,
        (ActorFunc)MmEnMkk_Destroy,
        (ActorFunc)MmEnMkk_Update,
        (ActorFunc)MmEnMkk_Draw,
        nullptr,
    };
    ActorDB::Instance->AddEntry(boe);

    // Generated by port_actor.py (M3 onwards).
#define MM_ACTOR(initVars, name, desc) RegisterGenerated(initVars, name, desc);
#include "MMPortActors.inc"
#undef MM_ACTOR
}

} // namespace MMPort
